import { Injectable, Logger } from '@nestjs/common';
import {
  AuthorType,
  GitRiskLevel,
  GitCommitAnalysis,
  PullRequestReviewInput,
  PullRequestReviewResult,
} from '@qualitypilot/types';

@Injectable()
export class DevIntelligenceEngine {
  private readonly logger = new Logger(DevIntelligenceEngine.name);

  /**
   * Evaluates Git Commit metadata and diff metrics for risk and AI-assisted heuristics.
   * STRICT PRINCIPLE: Always labels AI authorship indicators as evidence-based estimates, NOT definitive proof.
   */
  public analyzeCommit(commit: {
    hash: string;
    author: string;
    email: string;
    message: string;
    timestamp?: string;
    filesChanged: number;
    insertions: number;
    deletions: number;
    diffSnippet?: string;
  }): GitCommitAnalysis {
    this.logger.log(`Analyzing commit: ${commit.hash.substring(0, 7)} by ${commit.author}`);

    const evidenceFactors: string[] = [];
    let aiLikelihoodScore = 0; // 0 to 100

    // Heuristic 1: Semantic Commit Message analysis
    const msg = commit.message.toLowerCase();
    if (msg.includes('co-authored-by: copilot') || msg.includes('co-authored-by: cursor') || msg.includes('generated by claude')) {
      evidenceFactors.push('Explicit AI attribution token detected in commit body.');
      aiLikelihoodScore += 80;
    } else if (
      msg.startsWith('feat:') ||
      msg.startsWith('fix:') ||
      msg.startsWith('refactor:') ||
      msg.startsWith('chore:')
    ) {
      if (commit.message.length > 120 && commit.message.includes('\n- ')) {
        evidenceFactors.push('Highly structured bulleted changelog convention common in assisted workflows.');
        aiLikelihoodScore += 30;
      }
    }

    // Heuristic 2: Velocity / Diff Ratio
    const totalLines = commit.insertions + commit.deletions;
    if (commit.insertions > 400 && commit.deletions < 20) {
      evidenceFactors.push('High volume single-burst insertion ratio (>400 lines added with minimal edits).');
      aiLikelihoodScore += 25;
    }

    // Heuristic 3: Code Snippet Pattern Matching (Verbose boilerplate comments or synthetic function docs)
    const flags: string[] = [];
    let missingErrorHandling = false;
    let missingUnitTests = true;
    let suspiciousBoilerplate = false;
    let hallucinatedApiSignatures = false;

    if (commit.diffSnippet) {
      const diff = commit.diffSnippet;

      // Check comments density
      if (diff.includes('// Helper function to') || diff.includes('/** Auto-generated')) {
        evidenceFactors.push('Contains structured boilerplate commentary patterns.');
        aiLikelihoodScore += 20;
        suspiciousBoilerplate = true;
      }

      // Check test files presence
      if (diff.includes('.spec.') || diff.includes('.test.') || diff.includes('__tests__')) {
        missingUnitTests = false;
      }

      // Check error handling
      if ((diff.includes('async ') || diff.includes('fetch(') || diff.includes('axios.')) && !diff.includes('try {') && !diff.includes('.catch(')) {
        missingErrorHandling = true;
        flags.push('Uncaught async network/I/O call detected without try/catch block.');
      }

      // Check for hallucinated / non-existent mock imports
      if (diff.includes('from "non-existent-') || diff.includes('fake-sdk')) {
        hallucinatedApiSignatures = true;
        flags.push('Suspicious unknown third-party library reference detected.');
      }
    }

    // Clamp score
    aiLikelihoodScore = Math.min(Math.max(aiLikelihoodScore, 10), 95);

    let estimatedType = AuthorType.HUMAN;
    if (aiLikelihoodScore >= 65) {
      estimatedType = AuthorType.AI_ASSISTED;
    } else if (aiLikelihoodScore >= 40) {
      estimatedType = AuthorType.COLLABORATIVE_MIXED;
    }

    // Determine Risk Level
    let riskLevel = GitRiskLevel.LOW;
    if (missingErrorHandling || hallucinatedApiSignatures) {
      riskLevel = GitRiskLevel.HIGH;
    } else if (missingUnitTests && commit.insertions > 150) {
      riskLevel = GitRiskLevel.MEDIUM;
      flags.push('Substantial logic introduced without corresponding unit tests (.spec/.test).');
    }

    const recommendations: string[] = [];
    if (missingErrorHandling) {
      recommendations.push('Wrap asynchronous I/O and external API invocations in resilience blocks (try/catch + fallback).');
    }
    if (missingUnitTests) {
      recommendations.push('Enforce 80%+ test suite coverage on newly introduced modules before merge approval.');
    }
    if (estimatedType === AuthorType.AI_ASSISTED) {
      recommendations.push('Perform thorough edge-case code review on nullability, off-by-one errors, and boundary assumptions.');
    } else {
      recommendations.push('Standard peer review checklist: verify architectural consistency and security guidelines.');
    }

    return {
      commitHash: commit.hash,
      authorName: commit.author,
      authorEmail: commit.email,
      message: commit.message,
      timestamp: commit.timestamp || new Date().toISOString(),
      stats: {
        filesChanged: commit.filesChanged,
        insertions: commit.insertions,
        deletions: commit.deletions,
      },
      aiAuthorshipIndicators: {
        estimatedType,
        confidencePercentage: aiLikelihoodScore,
        evidenceFactors: evidenceFactors.length > 0 ? evidenceFactors : ['Standard human commit editing signature.'],
        disclaimer: 'Heuristic estimate based on commit semantics, comment patterns, and diff velocity. Not a cryptographic or infallible proof of authorship.',
      },
      qualityRisk: {
        riskLevel,
        hallucinatedApiSignaturesDetected: hallucinatedApiSignatures,
        missingErrorHandling,
        missingUnitTests,
        suspiciousBoilerplateDetected: suspiciousBoilerplate,
        flags,
      },
      reviewerRecommendations: recommendations,
    };
  }

  /**
   * Reviews an entire Pull Request payload with multi-file diff inspection.
   */
  public reviewPullRequest(pr: PullRequestReviewInput): PullRequestReviewResult {
    this.logger.log(`Performing intelligent QA review on PR: "${pr.title}"`);

    let totalAdditions = 0;
    let totalDeletions = 0;
    let hasTestFile = false;
    let hasPackageJsonChange = false;
    const findings: PullRequestReviewResult['criticalReviewFindings'] = [];

    for (const file of pr.changedFiles) {
      totalAdditions += file.additions;
      totalDeletions += file.deletions;

      if (file.filename.includes('test') || file.filename.includes('spec')) {
        hasTestFile = true;
      }
      if (file.filename.endsWith('package.json')) {
        hasPackageJsonChange = true;
      }

      if (file.patch) {
        if (file.patch.includes('password') && file.patch.includes('= "') && !file.patch.includes('process.env')) {
          findings.push({
            file: file.filename,
            finding: 'Potential plaintext credential assignment identified in diff.',
            suggestedFix: 'Extract secret into environment variables or Secret Manager.',
            severity: 'CRITICAL',
          });
        }

        if (file.patch.includes('any;') || file.patch.includes(': any')) {
          findings.push({
            file: file.filename,
            finding: 'Loose "any" typing detected, bypassing TypeScript strict compilation guarantee.',
            suggestedFix: 'Replace "any" with specific interface or "unknown" with validation.',
            severity: 'LOW',
          });
        }

        if (file.patch.includes('console.log(')) {
          findings.push({
            file: file.filename,
            finding: 'Production code contains unmanaged console.log statements.',
            suggestedFix: 'Use structured Logger service with log level filtering.',
            severity: 'INFO',
          });
        }
      }
    }

    const checklist = [
      {
        category: 'Test Coverage Verification',
        passed: hasTestFile || totalAdditions < 50,
        details: hasTestFile ? 'Test files modified/added in this PR.' : 'No automated tests included for new changes.',
      },
      {
        category: 'Dependency Hygiene',
        passed: !hasPackageJsonChange || pr.title.toLowerCase().includes('deps') || pr.title.toLowerCase().includes('bump'),
        details: hasPackageJsonChange ? 'Dependencies changed; verify lockfile integrity and CVE vulnerabilities.' : 'No new dependency risk.',
      },
      {
        category: 'Credential / Secret Exposure',
        passed: !findings.some((f) => f.severity === 'CRITICAL'),
        details: findings.some((f) => f.severity === 'CRITICAL') ? 'CRITICAL: Hardcoded secret detected in code diff!' : 'No hardcoded credentials found.',
      },
    ];

    // Estimate overall PR authorship distribution
    const aiIndicatorsCount = pr.commitMessages.filter((m) =>
      m.toLowerCase().includes('copilot') ||
      m.toLowerCase().includes('generated') ||
      m.toLowerCase().includes('cursor')
    ).length;

    let aiPercentage = aiIndicatorsCount > 0 ? 60 : totalAdditions > 300 && !hasTestFile ? 45 : 20;
    const humanPercentage = 100 - aiPercentage;

    let overallRiskLevel = GitRiskLevel.LOW;
    let mergeApprovalRecommendation: PullRequestReviewResult['mergeApprovalRecommendation'] = 'READY_TO_MERGE';

    if (findings.some((f) => f.severity === 'CRITICAL')) {
      overallRiskLevel = GitRiskLevel.HIGH;
      mergeApprovalRecommendation = 'BLOCK_MERGE';
    } else if (!hasTestFile && totalAdditions > 150) {
      overallRiskLevel = GitRiskLevel.MEDIUM;
      mergeApprovalRecommendation = 'REQUIRES_MANUAL_REVIEW';
    }

    return {
      summary: `Analyzed PR with ${pr.changedFiles.length} file(s), +${totalAdditions}/-${totalDeletions} lines changed. Overall Risk: ${overallRiskLevel}.`,
      overallRiskLevel,
      estimatedAuthorshipDistribution: {
        humanPercentage,
        aiAssistedPercentage: aiPercentage,
      },
      automatedChecklist: checklist,
      criticalReviewFindings: findings,
      mergeApprovalRecommendation,
    };
  }
}
